#!/usr/bin/env node
/**
 * Auto-generate index files for recorded fixtures
 * 
 * This script scans the clusters/ and subscriptions/ directories
 * and generates index.ts files that export all fixtures.
 * 
 * Run this after adding or removing fixture files.
 */

import { readdirSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const fixturesDir = join(__dirname, '../fixtures');

/**
 * Generate an index file for a subdirectory
 * @param {string} subdir - The subdirectory name (e.g., 'clusters', 'subscriptions')
 * @param {string} typeName - The type being exported (e.g., 'Cluster', 'Subscription')
 */
function generateIndex(subdir, typeName) {
  const dir = join(fixturesDir, subdir);
  
  try {
    // Read all .ts files except index.ts
    const files = readdirSync(dir)
      .filter(f => f.endsWith('.ts') && f !== 'index.ts')
      .sort();
    
    if (files.length === 0) {
      console.log(`ℹ️  No fixtures found in ${subdir}/`);
      
      // Create empty index
      const content = `/**
 * Auto-generated index of all recorded ${subdir} fixtures
 * 
 * This file exports all ${subdir} from this directory.
 * It's regenerated automatically by \`yarn msw:fixtures:build\`.
 * 
 * DO NOT EDIT THIS FILE MANUALLY!
 */

// No ${subdir} recorded yet
export {};
`;
      
      writeFileSync(join(dir, 'index.ts'), content);
      return;
    }
    
    console.log(`✅ Found ${files.length} fixture(s) in ${subdir}/:`);
    
    // Generate index content
    let content = `/**
 * Auto-generated index of all recorded ${subdir} fixtures
 * 
 * This file exports all ${subdir} from this directory.
 * It's regenerated automatically by \`yarn msw:fixtures:build\`.
 * 
 * DO NOT EDIT THIS FILE MANUALLY!
 * 
 * Generated: ${new Date().toISOString()}
 */

`;
    
    // Add re-exports
    files.forEach(file => {
      const baseName = file.replace('.ts', '');
      content += `export * from './${baseName}.js';\n`;
      console.log(`   - ${baseName}`);
    });
    
    writeFileSync(join(dir, 'index.ts'), content);
    console.log(`✅ Generated ${subdir}/index.ts\n`);
    
  } catch (error) {
    console.error(`❌ Error processing ${subdir}/:`, error.message);
  }
}

console.log('🔧 Generating fixture index files...\n');

generateIndex('clusters', 'Cluster');
generateIndex('subscriptions', 'Subscription');

console.log('🎉 Done!');

